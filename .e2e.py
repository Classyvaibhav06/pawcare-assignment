from playwright.sync_api import sync_playwright
B='http://127.0.0.1:8093/'; R=[]; errs=[]
def ok(c,m): R.append(('✓' if c else '✗')+' '+m)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox','--disable-dev-shm-usage'])
    for vp,tag in [((1366,860),'desk'),((390,844),'mob')]:
        ctx=b.new_context(viewport={'width':vp[0],'height':vp[1]},is_mobile=tag=='mob',has_touch=tag=='mob')
        pg=ctx.new_page(); pg.on('pageerror',lambda e,t=tag:errs.append(f'{t}: {e}'))
        pg.on('console',lambda m,t=tag:m.type=='error' and errs.append(f'{t} console: {m.text}'))
        # hub
        pg.goto(B); pg.wait_for_load_state('load'); pg.wait_for_timeout(500)
        ok(pg.locator('.strip img').count()==7 and pg.evaluate("[...document.querySelectorAll('.strip img')].every(i=>i.naturalWidth>0)"),f'{tag} hub: 7 carousel images load')
        ok(pg.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),f'{tag} hub: no horizontal overflow')
        # pawcare
        pg.goto(B+'pawcare/'); pg.wait_for_load_state('load'); pg.wait_for_timeout(500)
        ok(pg.locator('.pcard').count()==4,f'{tag} pawcare home: 4 top-rated cards')
        ok(pg.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),f'{tag} pawcare: no horizontal overflow')
        pg.fill('#hs input[name=q]','vaccination'); pg.click('#hs button'); pg.wait_for_timeout(300)
        n=pg.locator('#list .pcard').count(); ok('#/search' in pg.url and n>=1,f'{tag} search vaccination → {n} results, url={pg.url.split("#")[1]}')
        pg.goto(B+'pawcare/#/search?cat=hospital&emergency=1'); pg.wait_for_timeout(300)
        names=pg.locator('#list .pcard h3').all_inner_texts(); ok(len(names)==2 and all('Hospital' in x or 'Centre' in x for x in names),f'{tag} 24x7 hospitals filter → {names}')
        pg.goto(B+'pawcare/#/search?sp=Bird'); pg.wait_for_timeout(300)
        ok(pg.locator('#list .pcard').count()==3,f'{tag} species Bird → {pg.locator("#list .pcard").count()} (expect 3)')
        pg.goto(B+'pawcare/#/search?q=zzzz'); pg.wait_for_timeout(300); ok(pg.locator('.empty').count()==1,f'{tag} empty state')
        pg.goto(B+'pawcare/#/search'); pg.wait_for_timeout(300)
        if tag=='desk':
            pg.check('[data-f=open]'); pg.wait_for_timeout(300); ok('open=1' in pg.url and pg.locator('#list .pcard').count()==10,f'desk open-now checkbox → {pg.locator("#list .pcard").count()} (expect 10)')
            pg.select_option('#sort','fee'); pg.wait_for_timeout(300)
            fees=pg.locator('.side-actions > div > div:first-child').all_inner_texts(); ok(fees[0].startswith('Free'),f'desk sort by fee first={fees[0]}')
            ok(pg.locator('.pin').count()==10,'desk map pins match results')
        else:
            ok(pg.locator('#mobbar').is_visible(),'mob bottom bar visible'); pg.click('#mobbar button:first-child'); pg.wait_for_timeout(200)
            ok(pg.locator('#filters').is_visible(),'mob filters sheet opens')
            pg.click('#mobbar button:first-child')
        pg.locator('#list .pcard').first.locator('[data-book]').click(); pg.wait_for_timeout(200)
        ok(pg.locator('#bf').count()==1,f'{tag} booking modal opens')
        pg.fill('#bf [name=pet]','Bruno'); pg.fill('#bf [name=name]','Test'); pg.fill('#bf [name=phone]','123'); pg.click('#bf button.primary'); 
        ok('valid' in pg.inner_text('#berr'),f'{tag} bad phone rejected')
        pg.fill('#bf [name=phone]','9876543210'); pg.click('#bf button.primary'); pg.wait_for_timeout(200)
        ok('request sent' in pg.inner_text('.modal').lower() and pg.evaluate("JSON.parse(localStorage.pc_bookings).length")>=1,f'{tag} booking stored')
        pg.click('.modal [data-close].btn'); ok(pg.locator('.overlay').count()==0,f'{tag} modal closes')
        pg.goto(B+'pawcare/'); pg.wait_for_timeout(200)
        pg.locator('button[data-open=list]').first.click(); pg.fill('#lf [name=biz]','X Vet'); pg.fill('#lf [name=area]','HSR'); pg.fill('#lf [name=name]','Ravi K'); pg.fill('#lf [name=phone]','9123456789'); pg.click('#lf button')
        ok('PC-L' in pg.inner_text('.modal'),f'{tag} list-your-business ref issued'); pg.keyboard.press('Escape')
        pg.locator('button[data-open=correct]').first.click(); pg.fill('#cf [name=note]','closes 10pm'); pg.click('#cf button'); pg.wait_for_timeout(100)
        ok(pg.evaluate("JSON.parse(localStorage.pc_corrections).length")>=1,f'{tag} correction stored')
        pg.locator('.pcard').first.click(); pg.wait_for_timeout(150); ok('Last verified' in pg.inner_text('.modal'),f'{tag} detail sheet shows last-verified'); pg.keyboard.press('Escape')
        # academy
        pg.goto(B+'academy/'); pg.wait_for_load_state('load'); pg.wait_for_timeout(500)
        ok(pg.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),f'{tag} academy: no horizontal overflow')
        pg.click('[data-t=builder]'); pg.wait_for_timeout(200); ok('LLM APIs' in pg.inner_text('#weeks'),f'{tag} track switch rewrites curriculum')
        pg.wait_for_timeout(2500); ok('$' in pg.inner_text('#term'),f'{tag} terminal typing animates')
        pg.locator('[data-reg]').first.click(); pg.fill('#f1 [name=name]','Asha'); pg.fill('#f1 [name=email]','bad'); pg.click('#f1 button')
        ok('email' in pg.inner_text('#e1'),f'{tag} bad email rejected')
        pg.fill('#f1 [name=email]','asha@example.com'); pg.fill('#f1 [name=phone]','9988776655'); pg.click('#f1 button'); pg.wait_for_timeout(150)
        ok(pg.locator('#f2').count()==1 and pg.evaluate("JSON.parse(localStorage.aal_partial_leads).length")>=1,f'{tag} step1 → partial lead saved')
        pg.click('#f2 button.primary'); pg.wait_for_timeout(100); pg.click('#f3 button.primary'); pg.wait_for_timeout(150)
        ok('AAL-' in pg.inner_text('.modal') and 'AI Product Builder' in pg.inner_text('.modal'),f'{tag} application completes with chosen track')
        pg.keyboard.press('Escape')
        pg.locator('[data-enq]').first.click(); pg.fill('#fe [name=name]','Ravi'); pg.fill('#fe [name=phone]','8877665544'); pg.click('#fe button'); pg.wait_for_timeout(100)
        ok(pg.evaluate("JSON.parse(localStorage.aal_enquiries).length")>=1,f'{tag} enquiry stored')
        if tag=='mob': ok(pg.locator('.sticky-cta').is_visible(),'mob sticky apply bar visible')
        pg.goto(B+'pawcare/'); pg.screenshot(path=f'/tmp/ss_{tag}_pawcare.png'); pg.goto(B+'pawcare/#/search'); pg.wait_for_timeout(400); pg.screenshot(path=f'/tmp/ss_{tag}_search.png')
        pg.goto(B+'academy/'); pg.wait_for_timeout(600); pg.screenshot(path=f'/tmp/ss_{tag}_academy.png')
        pg.goto(B); pg.wait_for_timeout(600); pg.screenshot(path=f'/tmp/ss_{tag}_hub.png')
        ctx.close()
    b.close()
print('\n'.join(R)); print('PASS',sum(r[0]=='✓' for r in R),'/',len(R)); print('JS ERRORS:',errs or 'none')
